def daily_pick(items: list[str], day: str, category: str) -> dict[str, str]:
    """Раздаёт разные фразы знакам в пределах одной даты."""
    shuffled = list(items)
    seed = int(hashlib.sha256(f"{day}:{category}".encode()).hexdigest()[:16], 16)
    random.Random(seed).shuffle(shuffled)
    return dict(zip(SIGNS, shuffled))


def horoscope(sign: str, day: str) -> str:
    parts = [
        daily_pick(OPENERS, day, "openers")[sign],
        SIGN_FLAVOR[sign],
        daily_pick(SITUATIONS, day, "situations")[sign],
        daily_pick(MOODS, day, "moods")[sign],
        daily_pick(ADVICE, day, "advice")[sign],
    ]
    return "\n\n".join(parts)

def post_message(sign: str, day) -> str:
    date_text = day.strftime("%d.%m.%Y")
    text = horoscope(sign, day.isoformat())
    return (
        f"🔮 ГОРОСКОП НА {date_text}\n"
        f"ЗНАК: {sign.upper()}\n\n"
        f"{text}\n\n"
        "«Звёзды охуели» — юмор, а не руководство к жизни."
    )


def vk_call(token: str, method: str, params: dict) -> dict:
    response = requests.post(
        f"{VK_API}/{method}",
        data={**params, "access_token": token, "v": VK_VERSION},
        timeout=30,
    )
    response.raise_for_status()
    data = response.json()
    if "error" in data:
        error = data["error"]
        raise RuntimeError(f"VK API {error.get('error_code')}: {error.get('error_msg')}")
    return data["response"]

def main() -> None:
    token = os.getenv("VK_ACCESS_TOKEN", "").strip()
    group_id = os.getenv("VK_GROUP_ID", "243138653").strip()

    # Отдельный режим только для чтения: никаких публикаций и изменений в ВК.
    if os.getenv("VK_CHECK_ONLY", "false").lower() == "true":
        if not token:
            raise RuntimeError("Не задан VK_ACCESS_TOKEN в секретах GitHub.")
        if not group_id.isdigit():
            raise RuntimeError("VK_GROUP_ID должен быть числом без club.")
        group_data = vk_call(token, "groups.getById", {"group_id": group_id})
        group = group_data[0] if isinstance(group_data, list) else group_data
        print(f"Токен принят. Группа доступна: {group.get('name', group_id)}.")
        print("Проверка завершена. Стена не читалась, публикаций и изменений нет.")
        return

    today = datetime.now(TZ).date()

    # Предпросмотр формирует все тексты, но не обращается к VK API.
    if os.getenv("PREVIEW_ONLY", "false").lower() == "true":
        for sign in SIGNS:
            print("=" * 60)
            print(post_message(sign, today))
        print(f"Предпросмотр завершён: сформировано 12 гороскопов на {today:%d.%m.%Y}. Публикаций нет.")
        return

    if os.getenv("PUBLISH_ENABLED", "false").lower() != "true":
        print("Защита включена: PUBLISH_ENABLED не равен true. Публикаций нет.")
        return

    if not token:
        raise RuntimeError("Не задан VK_ACCESS_TOKEN в секретах GitHub.")
    if not group_id.isdigit():
        raise RuntimeError("VK_GROUP_ID должен быть числом без club.")

    # Планируем посты каждый час, начиная с 09:00. Если Actions опоздал,
    # сдвигаем всю серию целиком, сохраняя часовой интервал и порядок знаков.
    first_slot = datetime(today.year, today.month, today.day, 9, 0, tzinfo=TZ)
    first_publish = max(first_slot, datetime.now(TZ) + timedelta(minutes=2))
    for index, sign in enumerate(SIGNS):
        publish_at = first_publish + timedelta(hours=index)
        message = post_message(sign, today)
        vk_call(token, "wall.post", {
            "owner_id": -int(group_id),
            "from_group": 1,
            "message": message,
            "publish_date": int(publish_at.timestamp()),
            "guid": f"zvezdy-{today.isoformat()}-{index + 1}",
        })
        print(f"Запланирован пост: {sign}, {publish_at.isoformat()}")
        time.sleep(0.5)

    print(f"Готово: обработано 12 знаков на {today:%d.%m.%Y}.")

if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"ОШИБКА: {exc}", file=sys.stderr)
        raise
